"""Train or resume a class-weighted EfficientNetB0 DR classifier.

This is a separate experiment from the unweighted EfficientNet baseline. It
reuses the same model builder and official btgraham-300 splits. Class weights
are calculated from the selected training examples only and applied only to
the training loss through per-example sample weights. Undersampled runs read
the fixed manifest generated by prepare_undersampled_split.ipynb; this script
does not choose or drop random examples.
"""

